    private void Load_cboLopHoc() throws ClassNotFoundException{
        try {
            con = Connect.ConnectDB.KetnoiDB();
            String sql = "Select * From Lophoc";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            cbo_Lophoc.addItem("---Chọn lớp học---");
            lopHocMap.put("---Chọn lớp học---","");
            while(rs.next()){
                cbo_Lophoc.addItem(rs.getString("Tenlop"));
                lopHocMap.put(rs.getString("Tenlop"), rs.getString("Malop"));
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    
