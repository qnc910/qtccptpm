    private void btn_LuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_LuuActionPerformed
        // TODO add your handling code here:
        try{
        String masv = txt_Masinhvien.getText().trim();
        String hoten = txt_Hovaten.getText().trim();
        Date ngaysinh = new Date(txt_Ngaysinh.getDate().getTime());
        String gioitinh = cbo_Gioitinh.getSelectedItem().toString();
        String malop = lopHocMap.get(cbo_Lophoc.getSelectedItem().toString());
        String dienthoai = txt_Dienthoai.getText().trim();
        String email = txt_Email.getText().trim();
        String diachi = txt_Diachi.getText().trim();
        
        con = Connect.ConnectDB.KetnoiDB();
        String sql = "Insert into Sinhvien Values(?,?,?,?,?,?,?,?)";
        PreparedStatement ps = con.prepareStatement(sql);
        ps.setString(1, masv);
        ps.setString(2, hoten);
        ps.setDate(3, ngaysinh);
        ps.setString(4, gioitinh);
        ps.setString(5, malop);
        ps.setString(6, dienthoai);
        ps.setString(7, email);
        ps.setString(8, diachi);
        
        int kq = ps.executeUpdate();
            if (kq > 0) {
                JOptionPane.showMessageDialog(this, "Thêm thành công!");
            } else {
                JOptionPane.showMessageDialog(this, "Thêm thất bại!");
            }
            Load_Sinhvien();
            con.close();

        } catch(SQLException e){
            e.printStackTrace();
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(CapNhatSinhVien.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btn_LuuActionPerformed

    private void Load_Sinhvien(){
        try {
            tbl_SinhVien.removeAll();
            con = Connect.ConnectDB.KetnoiDB();
            String sql = "SELECT Masinhvien, Hoten, Ngaysinh, Gioitinh, sinhvien.Malop, lophoc.Tenlop, Dienthoai, Email, Diachi FROM sinhvien, lophoc WHERE sinhvien.Malop = lophoc.Malop";
            PreparedStatement ps = con.prepareStatement(sql);
            ResultSet rs = ps.executeQuery();
            String[] head = {"Mã sinh viên","Họ và tên","Ngày sinh","Giới tính","Mã lớp","Tên lớp","Điện thoại","Email","Địa chỉ"};
            DefaultTableModel tb = new DefaultTableModel(head, 0);
            while(rs.next()){
                Vector v = new Vector();
                v.add(rs.getString("Masinhvien"));
                v.add(rs.getString("Hoten"));
                v.add(rs.getString("Ngaysinh"));
                v.add(rs.getString("Gioitinh"));
                v.add(rs.getString("Malop"));
                v.add(rs.getString("Tenlop"));
                v.add(rs.getString("Dienthoai"));
                v.add(rs.getString("Email"));
                v.add(rs.getString("Diachi"));
                tb.addRow(v);
            }
            tbl_SinhVien.setModel(tb);
            con.close();
        } catch (Exception e) {
        }
    }
