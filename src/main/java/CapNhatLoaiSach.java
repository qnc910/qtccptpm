    private void btn_LuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_LuuActionPerformed
        // TODO add your handling code here:
        String maloai = txt_MaloaiUpdate.getText().trim();
        String tenloai = txt_TenLoaiUpdate.getText().trim();
        String mota = txt_MotaUpdate.getText().trim();

        if (maloai.isEmpty() || tenloai.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã loại và tên loại không được để trống");
            return;
        }

        if(checkTrungMaLoai(maloai)){
            JOptionPane.showMessageDialog(this, "Mã loại đã tồn tại");
            return;
        }
        try {
            Connection con = ConnectDB.KetnoiDB();
            String sql = "INSERT INTO loaisach (Maloai, Tenloai, Mota) VALUES (?, ?, ?)";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, maloai);
            pst.setString(2, tenloai);
            pst.setString(3, mota);

            int kq = pst.executeUpdate();
            if (kq > 0) {
                JOptionPane.showMessageDialog(this, "Thêm thành công!");
                load_loaisach();
            } else {
                JOptionPane.showMessageDialog(this, "Thêm thất bại!");
            }
            con.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi khi thêm dữ liệu: " + ex.getMessage());
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(CapNhatLoaiSach.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btn_LuuActionPerformed

