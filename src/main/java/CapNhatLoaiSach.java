    private void btn_TimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_TimKiemActionPerformed
        // TODO add your handling code here
        try {
            String maloai = txt_MaLoai.getText().trim();
            String tenloai = txt_TenLoai.getText().trim();
            //Kết nối DB;
            Connection con = ConnectDB.KetnoiDB();
            String sql = "SELECT * FROM loaisach WHERE Maloai LIKE ? AND Tenloai LIKE ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, '%' + maloai + '%');
            pst.setString(2, '%' + tenloai + '%');

            ResultSet rs = pst.executeQuery();
            tbLoaisach.removeAll();
            String[] head = {"Mã loại", "Tên loại", "Mô tả"};
            DefaultTableModel tb = new DefaultTableModel(head, 0);
            while(rs.next()){
                Vector v = new Vector<>();
                v.add(rs.getString("Maloai"));
                v.add(rs.getString("Tenloai"));
                v.add(rs.getString("Mota"));
                tb.addRow(v);
            }
            tbLoaisach.setModel(tb);
            con.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "TÌm kiếm thất bại: " + ex.getMessage());
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(CapNhatLoaiSach.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btn_TimKiemActionPerformed

    private  boolean checkTrungMaLoai(String maloai){
        boolean kq = false;
        try {
            Connection con = Connect.ConnectDB.KetnoiDB();
            String  sql = "SELECT * FROM loaisach WHERE Maloai = ?";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, maloai);
            ResultSet rs = ps.executeQuery();
            if(rs.next())
                kq = true;
        } catch (SQLException e) {
            e.printStackTrace();
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(CapNhatLoaiSach.class.getName()).log(Level.SEVERE, null, ex);
        }
        return kq;
    }
            
    private void load_loaisach() {
    try {
        Connection con = ConnectDB.KetnoiDB();
        String sql = "SELECT * FROM loaisach";
        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery(sql);
        DefaultTableModel tb = (DefaultTableModel) tbLoaisach.getModel();
        tb.setRowCount(0); // Xóa toàn bộ dữ liệu hiện tại trong bảng

        while (rs.next()) {
            Vector<String> v = new Vector<>();
            v.add(rs.getString("Maloai"));
            v.add(rs.getString("Tenloai"));
            v.add(rs.getString("Mota"));
            tb.addRow(v);
        }

        con.close();
    } catch (SQLException ex) {
        ex.printStackTrace();
    }   catch (ClassNotFoundException ex) {
            Logger.getLogger(CapNhatLoaiSach.class.getName()).log(Level.SEVERE, null, ex);
        }
}

    
