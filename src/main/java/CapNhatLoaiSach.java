    private void btn_XoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_XoaActionPerformed
        // TODO add your handling code here:
        String maloai = txt_MaloaiUpdate.getText().trim();

        if (maloai.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một loại sách để xóa.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa không?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) return;

        try {
            Connection con = ConnectDB.KetnoiDB();
            String sql = "DELETE FROM loaisach WHERE Maloai = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, maloai);

            int kq = pst.executeUpdate();
            if (kq > 0) {
                JOptionPane.showMessageDialog(this, "Xóa thành công!");
                load_loaisach();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại!");
            }
            con.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi khi xóa dữ liệu: " + ex.getMessage());
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(CapNhatLoaiSach.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btn_XoaActionPerformed

